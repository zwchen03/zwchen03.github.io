"""Fetch public LeetCode.cn profile data and write data/leetcode.js for the site.

Run locally (`python scripts/sync_leetcode.py`) or from the scheduled GitHub Action.
Standard library only.
"""
import json
import re
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

SLUG = "chun-qiu-kai-luo"
OUT = Path(__file__).resolve().parent.parent / "data" / "leetcode.js"


def gql(endpoint, query):
    req = urllib.request.Request(
        f"https://leetcode.cn/graphql/{endpoint}",
        data=json.dumps({"query": query, "variables": {"userSlug": SLUG}}).encode(),
        headers={
            "Content-Type": "application/json",
            "Referer": f"https://leetcode.cn/u/{SLUG}/",
            "User-Agent": "Mozilla/5.0",
        },
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        body = json.load(r)
    if body.get("errors"):
        raise RuntimeError(body["errors"])
    return body["data"]


def contest_name_en(title):
    m = re.search(r"第\s*(\d+)\s*场(双)?周赛", title)
    if m:
        return f"{'Biweekly' if m.group(2) else 'Weekly'} {m.group(1)}"
    return title


progress = gql("", """query($userSlug:String!){userProfileUserQuestionProgress(userSlug:$userSlug){
  numAcceptedQuestions{count difficulty} numFailedQuestions{count difficulty} numUntouchedQuestions{count difficulty}}}""")
contest = gql("noj-go/", """query($userSlug:String!){
  userContestRanking(userSlug:$userSlug){attendedContestsCount rating globalRanking globalTotalParticipants
    localRanking localTotalParticipants topPercentage}
  userContestRankingHistory(userSlug:$userSlug){attended rating ranking contest{title startTime}}}""")
calendar = gql("noj-go/", """query($userSlug:String!){userCalendar(userSlug:$userSlug){
  streak totalActiveDays recentStreak submissionCalendar}}""")["userCalendar"]

p = progress["userProfileUserQuestionProgress"]
solved = []
for diff in ("EASY", "MEDIUM", "HARD"):
    n = {k: next(x["count"] for x in p[k] if x["difficulty"] == diff)
         for k in ("numAcceptedQuestions", "numFailedQuestions", "numUntouchedQuestions")}
    solved.append({
        "name": diff.title(),
        "solved": n["numAcceptedQuestions"],
        "total": sum(n.values()),
    })

rank = contest["userContestRanking"]
history = [
    {
        "name": contest_name_en(h["contest"]["title"]),
        "nameZh": h["contest"]["title"],
        "time": h["contest"]["startTime"],
        "rating": round(h["rating"], 2),
        "ranking": h["ranking"],
    }
    for h in contest["userContestRankingHistory"] if h["attended"]
]

counts = {
    datetime.fromtimestamp(int(ts), timezone.utc).strftime("%Y-%m-%d"): n
    for ts, n in json.loads(calendar["submissionCalendar"]).items()
}

data = {
    "user": SLUG,
    "synced": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "solved": solved,
    "contest": {
        "rating": round(rank["rating"]),
        "attended": rank["attendedContestsCount"],
        "globalRanking": rank["globalRanking"],
        "globalTotal": rank["globalTotalParticipants"],
        "localRanking": rank["localRanking"],
        "localTotal": rank["localTotalParticipants"],
        "topPercentage": rank["topPercentage"],
        "history": history,
    },
    "calendar": {
        "activeDays": calendar["totalActiveDays"],
        "recentStreak": calendar["recentStreak"],
        "counts": dict(sorted(counts.items())),
    },
}

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// Generated by scripts/sync_leetcode.py. Do not edit by hand.\n"
    f"window.LEETCODE = {json.dumps(data, ensure_ascii=False, indent=1)};\n",
    encoding="utf-8",
)
print(f"wrote {OUT} ({sum(s['solved'] for s in solved)} solved, {sum(counts.values())} submissions)")
